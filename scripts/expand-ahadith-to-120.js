function main() {
  const existing = JSON.parse(fs.readFileSync(DATASET_PATH, 'utf8'));
  if (!Array.isArray(existing) || existing.length !== 60) {
    console.error(`Expected 60 existing hadiths, found ${existing?.length}`);
    process.exit(1);
  }
  if (NEW_HADITHS.length !== 60) {
    console.error(`Expected 60 new hadiths, found ${NEW_HADITHS.length}`);
    process.exit(1);
  }

  const upgraded = existing.map((item) => ({
    ...item,
    authenticity_grade: gradeFor(item),
  }));

  const appended = NEW_HADITHS.map((item, index) => {
    const id = 61 + index;
    const entry = {
      id,
      ...item,
      daily_index: id,
    };
    return entry;
  });

  const merged = [...upgraded, ...appended];
  fs.writeFileSync(DATASET_PATH, `${JSON.stringify(merged, null, 2)}\n`, 'utf8');
  console.log(`[expand-ahadith-to-120] Wrote ${merged.length} hadiths to ${DATASET_PATH}`);
  console.log(`[expand-ahadith-to-120] eid_al_fitr=${merged.filter((h) => h.special_days?.includes('eid_al_fitr')).length}`);
  console.log(`[expand-ahadith-to-120] daif=${merged.filter((h) => h.authenticity_grade === 'daif').length}`);
  console.log(`[expand-ahadith-to-120] salman/khorasan=${merged.filter((h) => h.topics?.some((t) => ['salman', 'khorasan'].includes(t))).length}`);
}

main();
