export type UiMessageKey = keyof typeof UI_MESSAGES;
export type UiMessageParams = Record<string, string | number>;

function fillParams(template: string, params: UiMessageParams): string {
  return template.replace(/\{(\w+)\}/g, (_match, name: string) => String(params[name] ?? `{${name}}`));
}

export function translateUi(
  key: UiMessageKey,
  language: AppLanguage,
  params: UiMessageParams = {},
): string {
  const entry = UI_MESSAGES[key] as UiMessage;
  // `satisfies` guarantees all three languages exist, but a stale persisted
  // language value must not blank out the UI.
  const template = entry[language] ?? entry.dari;
  return fillParams(template, params);
}

/** Look up a message in a specific language, honouring the content fallback. */
export function translateUiIn(
  key: UiMessageKey,
  language: AppLanguage,
  params: UiMessageParams = {},
): string {
  const entry = UI_MESSAGES[key] as UiMessage;
  for (const candidate of contentFallbackChain(language)) {
    const template = entry[candidate];
    if (template) return fillParams(template, params);
  }
  return key;
}
